def _list_outputs():
    ws = Path(SESSION.ensure_workspace())
    out = []
    for sub in ("outputs", ):
        d = ws / sub
        if not d.is_dir():
            continue
        for f in sorted(d.rglob("*")):
            if f.is_file():
                rel = f.relative_to(ws).as_posix()
                out.append((rel, f.stat().st_size))
    return out


